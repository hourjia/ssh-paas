/** 生成一段看起来"活着"的 CPU 曲线 */
const hist = (base: number, amp = 7, n = 26): number[] =>
  Array.from({ length: n }, (_, i) =>
    Math.max(2, Math.min(97, Math.round(base + Math.sin(i / 2.4) * amp + ((i * 31) % 9) - 4))),
  )

const env = (key: string, value: string, secret = false): EnvVar => ({ id: uid('env'), key, value, secret })
const port = (host: string, container: string): PortMap => ({ id: uid('pt'), host, container, protocol: 'TCP' })

function svc(partial: Partial<Service> & { name: string }): Service {
  return {
    id: uid('svc'),
    version: '1.0.0',
    sourceType: 'git',
    gitUrl: '',
    branch: 'main',
    localPath: '',
    dockerfile: './Dockerfile',
    envVars: [],
    ports: [],
    cpuLimit: 2,
    memLimit: 512,
    status: 'stopped',
    cpu: 0,
    mem: 0,
    cpuHistory: hist(6, 4),
    ...partial,
  }
}

